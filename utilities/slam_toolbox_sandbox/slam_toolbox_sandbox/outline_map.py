#!/usr/bin/env python3
"""
Turns a filled occupancy map into an outline map for localization.

Race stack maps mark the whole off-track area black. AMCL's likelihood field and the scan
matcher score a scan point by its distance to the nearest occupied pixel, which is 0 anywhere in
that area, so a point that overshoots a wall still counts as a perfect hit and a wrong pose is
hardly penalized. The lidar only ever sees wall faces, so this keeps only the occupied pixels
that touch free space (the same wall pixels png_to_world turns into Gazebo walls) and marks the
rest of the occupied area as unknown. Free space, resolution and origin are unchanged.

Usage:
    ros2 run slam_toolbox_sandbox outline_map --map-yaml <map>.yaml --out <outline>.yaml
"""
import argparse
import os

import numpy as np
import yaml
from PIL import Image

from slam_toolbox_sandbox.png_to_world import dilate, load_occupancy

# Pixel values of the output image. With the thresholds written below (and negate 0), 128 reads
# as unknown: occupancy (255 - 128) / 255 = 0.50 lies between free_thresh and occupied_thresh.
FREE, UNKNOWN, OCCUPIED = 255, 128, 0
FREE_THRESH, OCCUPIED_THRESH = 0.25, 0.65


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--map-yaml', required=True,
                        help='filled map .yaml (e.g. stack_master/maps/Victoria/Victoria.yaml)')
    parser.add_argument('--out', required=True, help='output .yaml; the image is written next to it as .png')
    parser.add_argument('--wall-thickness', type=int, default=2,
                        help='[pixels] into the occupied area. Keep it equal to png_to_world --wall-thickness')
    args = parser.parse_args()

    occupied, free, info = load_occupancy(args.map_yaml)
    walls = occupied & dilate(free, args.wall_thickness)   # same rule as png_to_world

    img = np.full(occupied.shape, UNKNOWN, dtype=np.uint8)
    img[free] = FREE
    img[walls] = OCCUPIED
    out_yaml = os.path.abspath(args.out)
    out_png = os.path.splitext(out_yaml)[0] + '.png'
    Image.fromarray(img).save(out_png)

    meta = {
        'image': os.path.basename(out_png),
        'mode': 'trinary',
        'resolution': info['resolution'],
        'origin': info['origin'],
        'negate': 0,
        'occupied_thresh': OCCUPIED_THRESH,
        'free_thresh': FREE_THRESH,
    }
    with open(out_yaml, 'w') as f:
        f.write(f'# Generated by outline_map from {os.path.basename(args.map_yaml)} '
                f'(wall thickness {args.wall_thickness} px): walls only, the rest of the\n'
                '# occupied area is unknown. Regenerate it instead of editing it.\n')
        yaml.safe_dump(meta, f, default_flow_style=None, sort_keys=False)
    print(f'kept {walls.sum()} of {occupied.sum()} occupied pixels as walls -> {out_yaml}')


if __name__ == '__main__':
    main()
