#!/usr/bin/env python3
"""
Turns a ROS occupancy map (map.yaml + image) into a Gazebo Fortress world.

Walls are placed only where occupied pixels touch free pixels, so maps whose
outside area is filled black do not become one solid block. Wall pixels are
merged into rectangles to keep the number of boxes small. The world frame
matches the map frame of the input map, so map coordinates (e.g. waypoints)
can be used directly as Gazebo poses.

Usage:
    ros2 run slam_toolbox_sandbox png_to_world --map-yaml <map>.yaml --out <world>.sdf
"""
import argparse
import os

import numpy as np
import yaml
from PIL import Image


def load_occupancy(map_yaml):
    with open(map_yaml) as f:
        info = yaml.safe_load(f)
    img_path = os.path.join(os.path.dirname(map_yaml), info['image'])
    img = np.array(Image.open(img_path).convert('L'), dtype=np.float64)
    # Same convention as nav2_map_server (trinary mode)
    p = img / 255.0 if info.get('negate', 0) else (255.0 - img) / 255.0
    occupied = p > info['occupied_thresh']
    free = p < info['free_thresh']
    return occupied, free, info


def dilate(mask, iterations):
    out = mask.copy()
    for _ in range(iterations):
        grown = out.copy()
        grown[1:, :] |= out[:-1, :]
        grown[:-1, :] |= out[1:, :]
        grown[:, 1:] |= out[:, :-1]
        grown[:, :-1] |= out[:, 1:]
        grown[1:, 1:] |= out[:-1, :-1]
        grown[1:, :-1] |= out[:-1, 1:]
        grown[:-1, 1:] |= out[1:, :-1]
        grown[:-1, :-1] |= out[1:, 1:]
        out = grown
    return out


def merge_rectangles(mask):
    """Greedy merge: horizontal runs per row, then stack identical runs of consecutive rows."""
    rects = []  # (row0, row1, col0, col1), inclusive
    open_runs = {}  # (col0, col1) -> row0
    for r in range(mask.shape[0] + 1):
        runs = set()
        if r < mask.shape[0]:
            row = mask[r]
            c = 0
            while c < row.size:
                if row[c]:
                    c0 = c
                    while c < row.size and row[c]:
                        c += 1
                    runs.add((c0, c - 1))
                else:
                    c += 1
        for run in list(open_runs):
            if run not in runs:
                rects.append((open_runs.pop(run), r - 1, run[0], run[1]))
        for run in runs:
            open_runs.setdefault(run, r)
    return rects


def build_world(rects, info, height, img_h, world_name, render_engine):
    res = info['resolution']
    ox, oy = info['origin'][0], info['origin'][1]
    boxes = []
    for i, (r0, r1, c0, c1) in enumerate(rects):
        x = ox + (c0 + c1 + 1) / 2.0 * res
        y = oy + (img_h - (r0 + r1 + 1) / 2.0) * res
        sx = (c1 - c0 + 1) * res
        sy = (r1 - r0 + 1) * res
        geom = f'<geometry><box><size>{sx:.4f} {sy:.4f} {height}</size></box></geometry>'
        boxes.append(
            f'        <collision name="c{i}"><pose>{x:.4f} {y:.4f} {height / 2} 0 0 0</pose>{geom}</collision>\n'
            f'        <visual name="v{i}"><pose>{x:.4f} {y:.4f} {height / 2} 0 0 0</pose>{geom}</visual>'
        )
    return f'''<?xml version="1.0"?>
<!-- Generated by png_to_world.py - do not edit by hand -->
<sdf version="1.8">
  <world name="{world_name}">
    <physics name="4ms" type="ignored">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>{render_engine}</render_engine>
    </plugin>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry></visual>
      </link>
    </model>

    <model name="walls">
      <static>true</static>
      <link name="link">
{chr(10).join(boxes)}
      </link>
    </model>
  </world>
</sdf>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--map-yaml', required=True, help='ROS map yaml (e.g. stack_master/maps/Victoria/Victoria.yaml)')
    parser.add_argument('--out', required=True, help='output .sdf world file')
    parser.add_argument('--world-name', default='track')
    parser.add_argument('--wall-height', type=float, default=0.4, help='[m]')
    parser.add_argument('--wall-thickness', type=int, default=2, help='[pixels] into the occupied area')
    parser.add_argument('--render-engine', default='ogre2', help="'ogre2' (default) or 'ogre' if ogre2 fails without a GPU")
    args = parser.parse_args()

    occupied, free, info = load_occupancy(args.map_yaml)
    if info['origin'][2] != 0:
        print('WARNING: map origin has a yaw, which is ignored - the world will be misaligned')
    walls = occupied & dilate(free, args.wall_thickness)
    rects = merge_rectangles(walls)
    sdf = build_world(rects, info, args.wall_height, occupied.shape[0], args.world_name, args.render_engine)
    with open(args.out, 'w') as f:
        f.write(sdf)
    print(f'{walls.sum()} wall pixels -> {len(rects)} boxes, written to {args.out}')


if __name__ == '__main__':
    main()
